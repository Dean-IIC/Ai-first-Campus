// Builds supabase/setup_all.sql: every migration plus all content from /content,
// so a new Supabase project can be set up by pasting ONE file into the SQL Editor.
// Usage: npm run db:sql            (includes rows marked "is_sample")
//        npm run db:sql -- --no-samples
import fs from "node:fs";
import path from "node:path";
import matter from "gray-matter";

const root = process.cwd();
const skipSamples = process.argv.includes("--no-samples");

const JSON_COLUMNS = new Set(["details", "photos"]);
const lit = (v, col) => {
  if (col && JSON_COLUMNS.has(col)) return `'${JSON.stringify(v ?? (col === "photos" ? [] : {})).replace(/'/g, "''")}'::jsonb`;
  if (v === null || v === undefined) return "null";
  if (typeof v === "number") return Number.isFinite(v) ? String(v) : "null";
  if (typeof v === "boolean") return v ? "true" : "false";
  if (Array.isArray(v)) return v.length ? `array[${v.map(lit).join(", ")}]::text[]` : "'{}'::text[]";
  if (typeof v === "object") return `'${JSON.stringify(v).replace(/'/g, "''")}'::jsonb`;
  return `'${String(v).replace(/'/g, "''")}'`;
};

const upsert = (table, rows, key = "slug") => {
  if (!rows.length) return `-- ${table}: no rows\n`;
  const cols = [...new Set(rows.flatMap((r) => Object.keys(r)))];
  const values = rows.map((r) => `  (${cols.map((c) => lit(r[c] ?? null, c)).join(", ")})`).join(",\n");
  const updates = cols.filter((c) => c !== key).map((c) => `${c} = excluded.${c}`).join(", ");
  // AI Champions and Ambassadors are edited on the website; never overwrite them when re-run.
  // Entries edited on the website (AI Champions, Ambassadors, the journey timeline) are never overwritten when this file is re-run.
  const onConflict = ["ai_people", "journey_milestones"].includes(table) ? "do nothing" : `do update set ${updates}`;
  return `insert into public.${table} (${cols.join(", ")}) values\n${values}\non conflict (${key}) ${onConflict};\n`;
};

const blank = (v) => (typeof v === "string" && v.trim() ? v.trim() : null);
const md = (dir) =>
  fs
    .readdirSync(path.join(root, "content", dir))
    .filter((f) => f.endsWith(".md"))
    .sort()
    .map((f) => {
      const { data, content } = matter(fs.readFileSync(path.join(root, "content", dir, f), "utf8"));
      return { slug: f.replace(/\.md$/, ""), data, body: content.trim() };
    });

let out = `-- HKBK College of Engineering website: complete database setup.
-- Paste this whole file into Supabase > SQL Editor > New query, then click Run.
-- It creates every table with row-level security, the storage bucket for images,
-- and loads all website content. Safe to run again: it updates rows instead of duplicating them.
-- Generated by scripts/build-setup-sql.mjs${skipSamples ? " (without sample rows)" : ""}.

begin;

`;

const migDir = path.join(root, "supabase", "migrations");
for (const f of fs.readdirSync(migDir).filter((f) => f.endsWith(".sql")).sort()) {
  out += `-- ============================================================\n-- Migration: ${f}\n-- ============================================================\n`;
  out += fs.readFileSync(path.join(migDir, f), "utf8").trim() + "\n\n";
}

out += `-- ============================================================\n-- Content\n-- ============================================================\n`;
out += upsert(
  "pages",
  md("pages").map((p) => ({ slug: p.slug, title: String(p.data.title ?? p.slug), summary: blank(p.data.summary), body_md: p.body })),
);
out += upsert(
  "leadership_messages",
  md("messages").map((m) => ({
    slug: m.slug,
    name: blank(m.data.name),
    designation: String(m.data.designation ?? m.slug),
    organisation: blank(m.data.organisation),
    excerpt: blank(m.data.excerpt),
    photo_url: blank(m.data.photo_url),
    body_md: m.body,
    sort_order: Number(m.data.sort_order ?? 99),
    section: blank(m.data.section) ?? "leadership",
  })),
);

const dataDir = path.join(root, "content", "data");
for (const f of fs.readdirSync(dataDir).filter((f) => f.endsWith(".json")).sort()) {
  let rows = JSON.parse(fs.readFileSync(path.join(dataDir, f), "utf8"));
  if (skipSamples) rows = rows.filter((r) => !r.is_sample);
  out += upsert(f.replace(/\.json$/, ""), rows);
}


out += "\ncommit;\n";
process.stdout.write(out);
